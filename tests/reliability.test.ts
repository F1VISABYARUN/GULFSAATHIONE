import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, readFileSync, writeFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { execFileSync } from 'node:child_process';

test('paired benchmark keeps labels blind, isolates speakers and scores reported, absent and unclear facts', t => {
  const dir = mkdtempSync(join(tmpdir(),'saathi-benchmark-'));
  t.after(()=>rmSync(dir,{recursive:true,force:true}));
  const file=join(dir,'labels.json'), catalog=join(dir,'calls.json');
  const run=(...args:string[])=>execFileSync(process.execPath,['--import','tsx','eval/reliability/run.ts',...args],{encoding:'utf8',stdio:['ignore','pipe','pipe']});
  const save=(data:unknown)=>writeFileSync(file,JSON.stringify(data));
  writeFileSync(catalog,JSON.stringify([{id8:'one',audio:'fixture.wav',turns:[{text:'లేదు',q:'మీ పాస్‌పోర్ట్ మీ దగ్గరే ఉందా?'}]}]));
  run('init',file,catalog);
  const [row]=JSON.parse(readFileSync(file,'utf8'));
  assert.equal(row.status,'pending'); assert.equal(row.text,undefined);assert.deepEqual(row.truth,{});
  assert.throws(()=>run('init',file,catalog),/EEXIST/);
  assert.equal(JSON.parse(run(file,'text','dev',catalog)).base,null);
  Object.assign(row,{status:'verified',speaker:'speaker-a',truth:{passportHeld:{state:'reported',value:true}}});
  save([row]);
  const replay=JSON.parse(run(file,'text','dev',catalog));
  assert.equal(replay.base.criticalFactAccuracy.count,0);assert.equal(replay.saathi.criticalFactAccuracy.count,1);
  assert.equal(replay.saathi.silentMiss,null);
  row.truth={feeINR:{state:'reported',value:100},salary:{state:'reported',value:{amount:1500,currency:'AED'}},visaType:{state:'absent'},passportHeld:{state:'unclear'}};
  row.risks=['UNPAID']; row.referenceText='one two';
  row.base={facts:{visaType:{state:'value',value:'visit',p:0.95}},asked:[],risks:['FALSE'],transcript:'one'};
  row.saathi={facts:{feeINR:{state:'value',value:100,p:0.95},passportHeld:{state:'unknown'}},asked:[['salary']],risks:['UNPAID'],transcript:'one two',extraSeconds:3};
  save([row]);
  const {base,saathi}=JSON.parse(run(file,'trace','dev'));
  assert.equal(base.silentMiss.rate,1);assert.equal(base.unsupported,1);assert.equal(base.calibration[2].accuracy,0);
  assert.equal(saathi.silentMiss.rate,0);assert.equal(saathi.criticalFactAccuracy.rate,0.5);
  assert.equal(saathi.flaggedUnresolved.count,1);assert.equal(saathi.byField.salary.accuracy.count,0);
  assert.equal(saathi.unknownPrecision.rate,1);assert.equal(saathi.unknownRecall.rate,0.5);
  assert.equal(saathi.calibration[2].meanConfidence,0.95);assert.equal(saathi.questionsPerCall,1);
  assert.equal(saathi.extraSecondsPerCall,3);assert.equal(base.extraSecondsPerCall,null);
  assert.equal(saathi.riskRecall.rate,1);assert.equal(base.falseAlarmsOnRiskLabeledTurns,1);assert.equal(base.normalizedWER.rate,0.5);
  save([row,{...row,call:'another',split:'heldout'}]);assert.throws(()=>run(file,'trace','dev'),/Split leakage/);
  save([row,row]);assert.throws(()=>run(file,'trace','dev'),/Duplicate turn/);
});
